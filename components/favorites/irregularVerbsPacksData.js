const _baseToPackId = new Map();
for (const pack of IRREGULAR_VERB_PACKS) {
  for (const verb of pack.verbs) {
    _baseToPackId.set(String(verb).toLowerCase(), pack.id);
  }
}

export function getIrregularPacksStrings(lang = 'en') {
  const norm = String(lang || 'en').toLowerCase().trim();
  const base = norm.split(/[-_]/)[0];
  const entry = IRREGULAR_PACKS_UI_I18N[norm] || IRREGULAR_PACKS_UI_I18N[base] || IRREGULAR_PACKS_UI_I18N.en;
  return { ...IRREGULAR_PACKS_UI_I18N.en, ...entry };
}

export function getLocalizedPackText(fieldObj, lang = 'en') {
  if (!fieldObj || typeof fieldObj !== 'object') return '';
  const norm = String(lang || 'en').toLowerCase().trim();
  const base = norm.split(/[-_]/)[0];
  return fieldObj[norm] || fieldObj[base] || fieldObj.en || '';
}

/**
 * Groups all irregular verbs (`category === 'Irregular verbs'`) into the 10 mnemonic pattern packs.
 * Any unmatched irregular verb falls back cleanly into `pack_aba_core` so zero verbs are ever lost.
 */
export function groupIrregularVerbsByPack(allWords = []) {
  const irregularWords = Array.isArray(allWords)
    ? allWords.filter((w) => w && w.category === 'Irregular verbs')
    : [];

  const buckets = new Map();
  for (const pack of IRREGULAR_VERB_PACKS) {
    buckets.set(pack.id, []);
  }

  for (const w of irregularWords) {
    const base = String(w.word || '').trim().split(/\s+/)[0].toLowerCase();
    const targetPackId = _baseToPackId.get(base) || 'pack_aba_core';
    buckets.get(targetPackId).push(w);
  }

  return IRREGULAR_VERB_PACKS.map((pack) => {
    const words = buckets.get(pack.id) || [];
    words.sort((a, b) => {
      const ba = String(a.word || '').trim().split(/\s+/)[0].toLowerCase();
      const bb = String(b.word || '').trim().split(/\s+/)[0].toLowerCase();
      const ia = pack.verbs.indexOf(ba);
      const ib = pack.verbs.indexOf(bb);
      if (ia !== -1 && ib !== -1 && ia !== ib) return ia - ib;
      if (ia !== -1 && ib === -1) return -1;
      if (ia === -1 && ib !== -1) return 1;
      return String(a.word || '').localeCompare(String(b.word || ''));
    });
    return {
      ...pack,
      words,
    };
  });
}
