// 36-locale auxiliary verb usage guide for all 16 tense constructions + Present Perfect "been to" vs "gone to" vs "been in" note.

function pickLocale(obj, lang = 'ru') {
  if (!obj) return '';
  const norm = String(lang || 'ru').toLowerCase().trim();
  if (obj[norm]) return obj[norm];
  const base = norm.split('-')[0];
  return obj[base] || obj.en || obj.ru || '';
}

