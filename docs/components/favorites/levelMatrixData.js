function safeReadJsonSet(storageKey, asNumbers = false) {
  try {
    if (typeof localStorage === 'undefined') return new Set();
    const raw = localStorage.getItem(storageKey);
    const parsed = raw ? JSON.parse(raw) : [];
    if (!Array.isArray(parsed)) return new Set();
    return new Set(asNumbers ? parsed.map(Number) : parsed.map(String));
  } catch (_) {
    return new Set();
  }
}

export function loadPassedCefrExams() {
  return safeReadJsonSet(STORAGE_KEY_CEFR_PASSED, false);
}

export function savePassedCefrExam(levelId) {
  const norm = String(levelId || '').toUpperCase().trim();
  if (!CEFR_LEVEL_BLUEPRINTS[norm]) return false;
  const set = loadPassedCefrExams();
  const newlyPassed = !set.has(norm);
  set.add(norm);
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(STORAGE_KEY_CEFR_PASSED, JSON.stringify([...set]));
    }
  } catch (_) {}
  return newlyPassed;
}

function pickLocale(map, lang = 'ru', fallback = 'en') {
  if (!map || typeof map !== 'object') return '';
  const norm = String(lang || 'ru').toLowerCase().trim();
  const base = norm.split(/[-_]/)[0];
  return map[norm] || map[base] || map[fallback] || map.en || map.ru || '';
}

function findGrammarGroupMeta(key) {
  const [kind, groupId] = String(key).split(':');
  if (kind === 'prepositions') {
    const grp = PREPOSITIONS_GROUPS.find((g) => g.id === groupId);
    return { kind, groupId, icon: grp?.icon || '🧭', titleMap: grp?.title, sectionId: null, items: grp?.items || [] };
  }
  if (kind === 'pronouns') {
    if (groupId === 'matrix') {
      return { kind, groupId, icon: '👤', isMatrix: true, titleMap: null, sectionId: null, items: [] };
    }
    const grp = PRONOUNS_GROUPS.find((g) => g.id === groupId);
    return { kind, groupId, icon: grp?.icon || '👤', titleMap: grp?.title, sectionId: null, items: grp?.items || [] };
  }
  if (kind === 'conjunctions') {
    for (const sec of CONJUNCTIONS_SECTIONS) {
      if (sec.id === groupId && !Array.isArray(sec.groups)) {
        return { kind, groupId, icon: sec.icon || '🔗', titleMap: sec.title, sectionId: sec.id, items: sec.items || [] };
      }
      if (Array.isArray(sec.groups)) {
        const grp = sec.groups.find((g) => g.id === groupId);
        if (grp) {
          return { kind, groupId, icon: grp.icon || sec.icon || '🔗', titleMap: grp.title, sectionId: sec.id, items: grp.items || [] };
        }
      }
    }
  }
  return { kind, groupId, icon: '📘', titleMap: null, sectionId: null, items: [] };
}

function countMastered(words, progress) {
  let count = 0;
  for (const w of words) {
    if (w && w.id != null && isWordMastered(progress[w.id])) {
      count++;
    }
  }
  return count;
}

export function computeLevelReadiness(levelId, allWords = [], lang = 'ru') {
  const normLevel = String(levelId || 'A1').toUpperCase().trim();
  const bp = CEFR_LEVEL_BLUEPRINTS[normLevel] || CEFR_LEVEL_BLUEPRINTS.A1;
  const s = getLevelMatrixStrings(lang);
  const profile = getCefrLevelProfile(normLevel, lang) || CEFR_LEVEL_PROFILE_I18N[normLevel] || {};

  let progress = {};
  try {
    progress = getUserProgress() || {};
  } catch (_) {}

  const microDone = safeReadJsonSet(STORAGE_KEY_MICRORULES_DONE, true);
  const tensesDone = safeReadJsonSet(STORAGE_KEY_TENSES_DONE, false);
  const gramRefDone = safeReadJsonSet(STORAGE_KEY_GRAMMAR_REF_DONE, false);
  const spokenDone = safeReadJsonSet(STORAGE_KEY_SPOKEN_PRACTICED, true);
  const completedCollectionsSet = safeReadJsonSet('myduo_completed_collections', false);
  const passedSet = loadPassedCefrExams();

  const wordsArr = Array.isArray(allWords) ? allWords : [];
  const packsGrouped = groupIrregularVerbsByPack(wordsArr);
  const blocks = [];

  // 1. Collections
  for (const col of bp.collections || []) {
    if (col.type === 'numbers_hub') {
      const numWords = [
        ...getCollectionWords('numbers', wordsArr),
        ...getCollectionWords('ordinal_numbers', wordsArr),
      ];
      const target = numWords.length > 0 ? numWords.length : col.fallbackTarget;
      const current = countMastered(numWords, progress);
      blocks.push({
        id: 'col:numbers_hub',
        category: 'collections',
        icon: col.icon || '🔢',
        title: s.numbers_hub,
        current,
        target,
        done: numWords.length > 0 && current >= target,
        linkTarget: { targetType: 'numbers_hub', targetId: 'numbers_hub' },
      });
    } else {
      const colWords = getCollectionWords(col.id, wordsArr);
      const rawTarget = colWords.length > 0 ? colWords.length : col.fallbackTarget;
      const target = col.targetCap ? Math.min(rawTarget, col.targetCap) : rawTarget;
      const rawMastered = countMastered(colWords, progress);
      const isMarkedColDone = !col.targetCap && completedCollectionsSet.has(String(col.id));
      const current = isMarkedColDone ? target : Math.min(rawMastered, target);
      const baseTitle = getCollectionTitle(col.id, lang) || col.id;
      const title = col.targetCap ? `${baseTitle} (${target})` : baseTitle;
      blocks.push({
        id: `col:${col.id}${col.targetCap ? `_${col.targetCap}` : ''}`,
        category: 'collections',
        icon: col.icon || '📚',
        title,
        current,
        target,
        done: isMarkedColDone || (colWords.length > 0 && current >= target),
        linkTarget: { targetType: 'collection', targetId: col.id },
      });
    }
  }

  // 2. Dictionary Vocabulary Milestone
  const totalMastered = wordsArr.length > 0 ? countMastered(wordsArr, progress) : 0;
  const vocabTarget = profile.vocabTargetWords || 1000;
  blocks.push({
    id: `cefr_vocab:${normLevel}`,
    category: 'vocabulary',
    icon: '🧠',
    title: s.vocabTargetBlockTitle.replace('{level}', normLevel).replace('{target}', String(vocabTarget)),
    current: Math.min(totalMastered, vocabTarget),
    target: vocabTarget,
    done: totalMastered >= vocabTarget,
    linkTarget: {
      targetType: 'dictionary',
      category: normLevel === 'A1' || normLevel === 'A2' ? 'Elementary' : normLevel === 'B1' || normLevel === 'B2' ? 'Intermediate' : 'Advanced',
    },
  });

  if (bp.vocabCategory) {
    const vc = bp.vocabCategory;
    const catWords = wordsArr.filter((w) => w && w.category === vc.category);
    const target = catWords.length > 0 ? catWords.length : vc.fallbackTarget;
    const current = countMastered(catWords, progress);
    blocks.push({
      id: `vocab:${vc.category}`,
      category: 'vocabulary',
      icon: vc.icon || '📖',
      title: s[vc.key] || vc.category,
      current,
      target,
      done: catWords.length > 0 && current >= target,
      linkTarget: { targetType: 'dictionary', targetId: vc.category, category: vc.category },
    });
  }

  // 3. Grammar Reference (Prepositions, Pronouns, Conjunctions)
  if (bp.grammarRefAll) {
    const target = ALL_GRAMMAR_REF_KEYS.length;
    const current = ALL_GRAMMAR_REF_KEYS.filter((k) => gramRefDone.has(k)).length;
    blocks.push({
      id: 'gref:all',
      category: 'grammar_ref',
      icon: '🧭',
      title: s.grammar_ref_all,
      current,
      target,
      done: target > 0 && current >= target,
      linkTarget: { targetType: 'grammar_prepositions', targetGroup: 'all' },
    });
  } else {
    for (const key of bp.grammarRef || []) {
      const meta = findGrammarGroupMeta(key);
      const kindLabel =
        meta.kind === 'prepositions'
          ? s.grammar_prep
          : meta.kind === 'pronouns'
            ? s.grammar_pron
            : s.grammar_conj;
      const groupTitle = meta.isMatrix
        ? getPronounMatrixLabel(lang)
        : pickLocale(meta.titleMap, lang, 'en') || meta.groupId;
      const done = gramRefDone.has(key);
      const targetType =
        meta.kind === 'prepositions'
          ? 'grammar_prepositions'
          : meta.kind === 'pronouns'
            ? 'grammar_pronouns'
            : 'grammar_conjunctions';
      blocks.push({
        id: `gref:${key}`,
        category: 'grammar_ref',
        icon: meta.icon,
        title: `${kindLabel}: ${groupTitle}`,
        current: done ? 1 : 0,
        target: 1,
        done,
        linkTarget: {
          targetType,
          targetGroup: meta.groupId,
          ...(meta.sectionId ? { targetId: meta.sectionId } : {}),
        },
      });
    }
  }

  // 4. Irregular Verb Packs
  if (bp.irregularPacksAll) {
    const allIrrWords = packsGrouped.flatMap((p) => p.words || []);
    const target = allIrrWords.length > 0 ? allIrrWords.length : 149;
    const current = countMastered(allIrrWords, progress);
    blocks.push({
      id: 'irr:all',
      category: 'irregular',
      icon: '⚡',
      title: s.irregular_all,
      current,
      target,
      done: allIrrWords.length > 0 && current >= target,
      linkTarget: { targetType: 'irregular_verbs_packs', packId: 'all' },
    });
  } else {
    for (const packId of bp.irregularPacks || []) {
      const pack = packsGrouped.find((p) => p.id === packId);
      if (!pack) continue;
      const target = pack.words.length > 0 ? pack.words.length : pack.verbs.length;
      const current = countMastered(pack.words, progress);
      const packTitle = pickLocale(pack.title, lang, 'en') || pack.pattern || pack.id;
      blocks.push({
        id: `irr:${pack.id}`,
        category: 'irregular',
        icon: pack.icon || '⚡',
        title: packTitle,
        current,
        target,
        done: pack.words.length > 0 && current >= target,
        linkTarget: { targetType: 'irregular_verbs_packs', packId: pack.id, targetId: pack.id },
      });
    }
  }

  // 5. Tense Constructions
  if (bp.tenseAll) {
    const target = TENSE_CONSTRUCTIONS.length;
    const current = TENSE_CONSTRUCTIONS.filter((t) => tensesDone.has(t.id)).length;
    blocks.push({
      id: 'tenses:all',
      category: 'tenses',
      icon: '⏳',
      title: s.tenses_all,
      current,
      target,
      done: target > 0 && current >= target,
      linkTarget: {
        targetType: 'tense_construction',
        targetId: 'future_perfect_continuous',
        level: 'C1',
      },
    });
  } else if (bp.tenseLevel) {
    const levelTenses = TENSE_CONSTRUCTIONS.filter((t) => t.level === bp.tenseLevel);
    const target = levelTenses.length;
    const current = levelTenses.filter((t) => tensesDone.has(t.id)).length;
    blocks.push({
      id: `tenses:${bp.tenseLevel}`,
      category: 'tenses',
      icon: '⏳',
      title: s.tenses_block.replace('{level}', bp.tenseLevel),
      current,
      target,
      done: target > 0 && current >= target,
      linkTarget: {
        targetType: 'tense_construction',
        targetId: levelTenses[0]?.id || 'present_simple',
        level: bp.tenseLevel,
      },
    });
  }

  // 6. Micro-rules
  if (bp.microRuleAll) {
    const target = MICRO_RULES.length;
    const current = MICRO_RULES.filter((r) => microDone.has(r.id)).length;
    blocks.push({
      id: 'microrules:all',
      category: 'microrules',
      icon: '📘',
      title: s.microrules_all,
      current,
      target,
      done: target > 0 && current >= target,
      linkTarget: { targetType: 'grammar_microrules', level: 'B2' },
    });
  } else if (bp.microRuleLevel) {
    const levelRules = MICRO_RULES.filter((r) => r.level === bp.microRuleLevel);
    const target = levelRules.length;
    const current = levelRules.filter((r) => microDone.has(r.id)).length;
    blocks.push({
      id: `microrules:${bp.microRuleLevel}`,
      category: 'microrules',
      icon: '📘',
      title: s.microrules_block.replace('{level}', bp.microRuleLevel),
      current,
      target,
      done: target > 0 && current >= target,
      linkTarget: { targetType: 'grammar_microrules', level: bp.microRuleLevel },
    });
  }

  // 7. Spoken English
  if (bp.spokenAll) {
    const target = SPOKEN_ENGLISH_ITEMS.length;
    const current = SPOKEN_ENGLISH_ITEMS.filter((it) => spokenDone.has(it.id)).length;
    blocks.push({
      id: 'spoken:all',
      category: 'spoken',
      icon: '🗣️',
      title: s.spoken_all,
      current,
      target,
      done: target > 0 && current >= target,
      linkTarget: { targetType: 'spoken_english', category: 'all' },
    });
  } else {
    for (const cat of bp.spokenCategories || []) {
      const catItems = SPOKEN_ENGLISH_ITEMS.filter((it) => it.category === cat);
      const target = catItems.length;
      const current = catItems.filter((it) => spokenDone.has(it.id)).length;
      blocks.push({
        id: `spoken:${cat}`,
        category: 'spoken',
        icon: '🗣️',
        title: `${s.spoken_block}: ${s.spokenCats[cat] || cat}`,
        current,
        target,
        done: target > 0 && current >= target,
        linkTarget: { targetType: 'spoken_english', category: cat },
      });
    }
  }

  const totalBlocks = blocks.length;
  const closedBlocks = blocks.filter((b) => b.done).length;
  const percent = totalBlocks > 0 ? Math.round((closedBlocks / totalBlocks) * 100) : 0;

  return {
    levelId: normLevel,
    totalBlocks,
    closedBlocks,
    percent,
    examPassed: passedSet.has(normLevel),
    vocabRange: profile.vocabRange || '',
    vocabTargetWords: profile.vocabTargetWords || 500,
    skills: profile.skills || '',
    blocks,
  };
}

function shuffleArray(arr) {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

function getAllItemsForKind(kind) {
  if (kind === 'prepositions') {
    return PREPOSITIONS_GROUPS.flatMap((g) => g.items || []);
  }
  if (kind === 'pronouns') {
    const list = [...PRONOUNS_GROUPS.flatMap((g) => g.items || [])];
    for (const row of PRONOUNS_MATRIX.rows) {
      for (const col of ['subject', 'object', 'possessiveDep', 'possessiveAbs', 'reflexive']) {
        if (row[col]?.word) list.push(row[col]);
      }
    }
    return list;
  }
  const list = [];
  for (const sec of CONJUNCTIONS_SECTIONS) {
    if (Array.isArray(sec.items)) list.push(...sec.items);
    if (Array.isArray(sec.groups)) {
      for (const g of sec.groups) list.push(...(g.items || []));
    }
  }
  return list;
}

const ALL_PREP_ITEMS = getAllItemsForKind('prepositions');
const ALL_PRON_ITEMS = getAllItemsForKind('pronouns');
const ALL_CONJ_ITEMS = getAllItemsForKind('conjunctions');

function buildGrammarRefQuestion(key, lang, s, block, idx) {
  const meta = findGrammarGroupMeta(key);
  let items = meta.items;
  if (meta.isMatrix) {
    items = [];
    for (const row of PRONOUNS_MATRIX.rows) {
      for (const col of ['subject', 'object', 'possessiveDep', 'possessiveAbs', 'reflexive']) {
        if (row[col]?.word) items.push(row[col]);
      }
    }
  }
  if (!items.length) return null;
  const picked = shuffleArray(items)[0];
  const answer = String(picked.word || '').trim();
  const meaning = pickLocale(picked.tr, lang, 'en') || answer;
  if (!answer || !meaning) return null;

  const pool =
    meta.kind === 'prepositions'
      ? ALL_PREP_ITEMS
      : meta.kind === 'pronouns'
        ? ALL_PRON_ITEMS
        : ALL_CONJ_ITEMS;

  const distractors = [];
  const seen = new Set([answer.toLowerCase()]);
  for (const cand of shuffleArray(pool)) {
    const w = String(cand.word || '').trim();
    if (!w || seen.has(w.toLowerCase())) continue;
    seen.add(w.toLowerCase());
    distractors.push(w);
    if (distractors.length >= 3) break;
  }
  if (distractors.length < 3) return null;

  const groupName = meta.isMatrix ? getPronounMatrixLabel(lang) : pickLocale(meta.titleMap, lang, 'en') || meta.groupId;
  const tpl =
    meta.kind === 'prepositions'
      ? s.prepPrompt
      : meta.kind === 'pronouns'
        ? s.pronPrompt
        : s.conjPrompt;

  // Prefer cloze blanking when example cleanly contains the single word
  let prompt = tpl.replace('{group}', groupName).replace('{meaning}', meaning);
  if (picked.example && !answer.includes('/') && !answer.includes(' ')) {
    const re = new RegExp(`\\b${answer.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'i');
    if (re.test(picked.example)) {
      const blanked = picked.example.replace(re, '___');
      prompt = `${blanked} (${meaning})`;
    }
  }

  return {
    id: `q_gref_${key}_${idx}`,
    type: 'choice',
    blockId: block.id,
    blockTitle: block.title,
    category: 'grammar_ref',
    linkTarget: block.linkTarget,
    prompt,
    answer,
    options: shuffleArray([answer, ...distractors]),
  };
}

function buildIrregularQuestion(packId, packsGrouped, lang, s, block, idx) {
  const targetPackId = packId === 'all'
    ? shuffleArray(IRREGULAR_VERB_PACKS)[0].id
    : packId;
  const grouped = packsGrouped.find((p) => p.id === targetPackId);
  const triples = [];

  if (grouped && grouped.words.length > 0) {
    for (const w of grouped.words) {
      const parts = String(w.word || '').trim().split(/\s+/).filter(Boolean);
      if (parts.length >= 3) {
        triples.push([parts[0], parts[1], parts.slice(2).join(' ')]);
      }
    }
  }
  if (triples.length < 2) {
    for (const t of BUILTIN_IRREGULAR_TRIPLES[targetPackId] || BUILTIN_IRREGULAR_TRIPLES.pack_aba_core) {
      triples.push(t);
    }
  }

  const chosen = shuffleArray(triples)[0];
  if (!chosen) return null;
  const [v1, v2, v3] = chosen;
  const answer = `${v2} — ${v3}`;
  const seen = new Set([answer.toLowerCase()]);
  const distractors = [];

  const candidateFakePairs = [
    `${v1}ed — ${v1}ed`,
    `${v3} — ${v2}`,
    `${v1} — ${v2}`,
    `${v2}en — ${v2}`,
  ];
  for (const fp of candidateFakePairs) {
    if (!seen.has(fp.toLowerCase())) {
      seen.add(fp.toLowerCase());
      distractors.push(fp);
      if (distractors.length >= 3) break;
    }
  }
  if (distractors.length < 3) {
    for (const other of Object.values(BUILTIN_IRREGULAR_TRIPLES).flat()) {
      const cand = `${other[1]} — ${other[2]}`;
      if (!seen.has(cand.toLowerCase())) {
        seen.add(cand.toLowerCase());
        distractors.push(cand);
        if (distractors.length >= 3) break;
      }
    }
  }

  return {
    id: `q_irr_${targetPackId}_${idx}`,
    type: 'choice',
    blockId: block.id,
    blockTitle: block.title,
    category: 'irregular',
    linkTarget: block.linkTarget,
    prompt: s.verbFormsPrompt.replace('{v1}', v1),
    answer,
    options: shuffleArray([answer, ...distractors.slice(0, 3)]),
  };
}

function buildVocabQuestion(wordsPool, allPool, lang, s, block, idx) {
  if (!wordsPool.length) return null;
  const candidates = shuffleArray(wordsPool);
  for (const w of candidates) {
    const ans = String(getWordTranslation(w, lang) || w.translation || '').trim();
    if (!ans || ans.toLowerCase() === String(w.word || '').toLowerCase()) continue;
    const seen = new Set([ans.toLowerCase()]);
    const distractors = [];
    for (const other of shuffleArray(allPool)) {
      const tr = String(getWordTranslation(other, lang) || other.translation || '').trim();
      if (!tr || seen.has(tr.toLowerCase())) continue;
      seen.add(tr.toLowerCase());
      distractors.push(tr);
      if (distractors.length >= 3) break;
    }
    if (distractors.length === 3) {
      const exp = w.example
        ? `${w.word} — ${ans} (${w.example})`
        : `${w.word} — ${ans}`;
      return {
        id: `q_vocab_${block.id}_${idx}`,
        type: 'choice',
        topicId: block.id,
        topicTitle: block.title,
        blockId: block.id,
        blockTitle: block.title,
        category: block.category,
        microRuleId: block.microRuleId || null,
        linkTarget: block.linkTarget,
        prompt: s.vocabPrompt.replace('{word}', w.word),
        answer: ans,
        options: shuffleArray([ans, ...distractors]),
        explanation: exp,
        _wordKey: String(w.word || '').toLowerCase().trim(),
      };
    }
  }
  return null;
}

function buildTenseQuestion(tensePool, block, idx) {
  const pool = shuffleArray(tensePool);
  for (const tObj of pool) {
    const q = shuffleArray(tObj.quiz || [])[0];
    if (q && q.blanked && q.answer && Array.isArray(q.options) && new Set(q.options).size === 4) {
      return {
        id: `q_tense_${tObj.id}_${idx}`,
        type: 'choice',
        blockId: block.id,
        blockTitle: block.title,
        category: 'tenses',
        linkTarget: { targetType: 'tense_construction', targetId: tObj.id, level: tObj.level },
        prompt: `[${tObj.title}] ${q.blanked}`,
        answer: q.answer,
        options: shuffleArray(q.options),
      };
    }
  }
  return null;
}

