function t36(vals) {
  const out = {};
  for (let i = 0; i < LOCS.length; i++) {
    out[LOCS[i]] = vals[i];
  }
  return out;
}

function cell(word, vals) {
  return { word, tr: t36(vals) };
}

function item(word, vals, example) {
  return { word, tr: t36(vals), example };
}

