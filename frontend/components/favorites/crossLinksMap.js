/**
 * Resolve cross-links from a micro-rule to related collections, grammar matrices, and tense constructions.
 * @param {number|string} ruleId
 * @param {string} [topic]
 * @returns {Array<object>}
 */
export function getRelatedLinksForMicroRule(ruleId, topic = '') {
  const id = Number(ruleId);
  const t = String(topic || '').trim();
  const links = [];

  // 1. Numbers hub
  if (id === 6) {
    links.push({ targetType: 'numbers_hub', icon: '🔢', labelKey: 'numbersHub' });
  }

  // 2. Prepositions
  if (t === 'prepositions' || PREPOSITION_RULE_IDS.has(id)) {
    let targetGroup = 'all';
    if (PREPOSITION_TIME_IDS.has(id)) targetGroup = 'time';
    else if (PREPOSITION_PLACE_IDS.has(id)) targetGroup = 'place';
    else if (id === 28) targetGroup = 'direction';
    else if (id === 29) targetGroup = 'manner';
    else if (id === 30) targetGroup = 'topic';
    links.push({ targetType: 'grammar_prepositions', targetGroup, icon: '🧭', labelKey: 'prepositions' });
  }

  // 3. Pronouns
  if (t === 'pronouns' || PRONOUN_RULE_IDS.has(id)) {
    let targetGroup = 'all';
    if (PRONOUN_MATRIX_IDS.has(id)) targetGroup = 'matrix';
    else if (id === 16) targetGroup = 'demonstrative';
    else if (PRONOUN_INTERROGATIVE_IDS.has(id)) targetGroup = 'interrogative';
    else if (PRONOUN_RELATIVE_IDS.has(id)) targetGroup = 'relative';
    else if (PRONOUN_INDEFINITE_IDS.has(id)) targetGroup = 'indefinite';
    else if (PRONOUN_UNIVERSAL_IDS.has(id)) targetGroup = 'universal';
    links.push({ targetType: 'grammar_pronouns', targetGroup, icon: '👤', labelKey: 'pronouns' });
  }

  // 4. Conjunctions & contrast
  if (t === 'conjunctions_contrast' || CONJUNCTION_RULE_IDS.has(id)) {
    let targetGroup = 'subordinating';
    if (CONJUNCTIVE_ADVERB_IDS.has(id)) targetGroup = 'conjunctive_adverbs';
    else if (id === 107) targetGroup = 'correlative';
    links.push({ targetType: 'grammar_conjunctions', targetGroup, icon: '🔗', labelKey: 'conjunctions' });
  }

  // 5. Irregular verbs (+ verbs collection for rule 2)
  if (IRREGULAR_VERB_RULE_IDS.has(id)) {
    links.push({ targetType: 'irregular_verbs_packs', icon: '⚡', labelKey: 'irregularVerbs' });
    if (id === 2) {
      links.push({ targetType: 'collection', targetId: 'verbs', icon: '⚡', labelKey: 'verbsCol' });
    }
  }

  // 6. Phrasal verbs
  if (t === 'phrasal_verbs' || PHRASAL_VERB_RULE_IDS.has(id)) {
    links.push({ targetType: 'collection', targetId: 'phrasal_verbs', icon: '🔄', labelKey: 'phrasalVerbsCol' });
  }

  // 7. Tricky pairs / confusing words
  if (t === 'tricky_pairs' || TRICKY_PAIR_RULE_IDS.has(id)) {
    links.push({ targetType: 'collection', targetId: 'confusing_words', icon: '🤔', labelKey: 'confusingWordsCol' });
  }

  // 8. Adjectives & comparatives
  if (t === 'adjectives_adverbs' || t === 'comparatives' || ADJECTIVE_RULE_IDS.has(id)) {
    links.push({ targetType: 'collection', targetId: 'adjectives', icon: '🌟', labelKey: 'adjectivesCol' });
  }

  // 9. Days of week & months for Rule 31
  if (id === 31) {
    links.push({ targetType: 'collection', targetId: 'days_of_week', icon: '📅', labelKey: 'daysOfWeekCol' });
    links.push({ targetType: 'collection', targetId: 'months', icon: '🗓️', labelKey: 'monthsCol' });
  }

  // 10. Tense constructions
  if (TENSE_MICRO_RULE_MAP[id]) {
    links.push({
      targetType: 'tense_construction',
      targetId: TENSE_MICRO_RULE_MAP[id],
      icon: '⏳',
      labelKey: 'tenseConstruction',
    });
  }

  return links;
}

