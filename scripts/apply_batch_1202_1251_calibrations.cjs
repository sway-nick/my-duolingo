let updatedWords = 0;
let updatedFields = 0;

for (const [idStr, cal] of Object.entries(calibrations)) {
  const id = parseInt(idStr, 10);
  const w = words.find(item => item.id === id);
  if (!w) {
    console.warn(`Word with ID ${id} not found in words.json`);
    continue;
  }

  let changed = false;

  // ru update
  if (cal.ru && w.translation !== cal.ru) {
    w.translation = cal.ru;
    changed = true;
    updatedFields++;
  }

  // 34 translations check
  for (const [lang, val] of Object.entries(cal)) {
    if (lang === 'ru') continue;
    if (!w.translations) w.translations = {};
    if (w.translations[lang] !== val) {
      w.translations[lang] = val;
      changed = true;
      updatedFields++;
    }
  }

  if (changed) {
    updatedWords++;
  }
}

