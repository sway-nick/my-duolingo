export function applySpanishRefinements() {
  console.log('Applying concise Spanish vocabulary refinements...');
  
  const wordsPath = WORDS_JSON_FILES[0];
  const words = JSON.parse(fs.readFileSync(wordsPath, 'utf8'));

  let appliedCount = 0;
  for (const w of words) {
    if (SPANISH_WORD_REFINEMENTS[w.id]) {
      const refined = SPANISH_WORD_REFINEMENTS[w.id];
      w.translations = w.translations || {};
      if (w.translations.es !== refined) {
        w.translations.es = refined;
        appliedCount++;
      }
    }
  }

  const jsonStr = JSON.stringify(words);
  if (jsonStr.includes('\ufffd')) {
    throw new Error('Detected U+FFFD replacement characters!');
  }

  WORDS_JSON_FILES.forEach(filePath => {
    fs.writeFileSync(filePath, jsonStr, 'utf8');
    console.log(`Saved: ${filePath}`);
  });

  console.log(`Successfully refined ${appliedCount} Spanish entries across all words.json files.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  applySpanishRefinements();
}
